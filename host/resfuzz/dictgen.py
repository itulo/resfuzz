"""Dictionary / seed generation from a resource manager's devctl header.

Three stages, the first two deterministic:
 1. parse_header(): find `#define NAME __DIOT|__DIOF|__DIOTF|__DION(class, cmd[, type])`
    (macros documented at
    https://www.qnx.com/developers/docs/8.0/com.qnx.doc.neutrino.lib_ref/topic/d/devctl.html)
    plus numeric / string constants (magic values, flags) for the token dictionary.
 2. resolver_source(): emit a C program that includes the real header and prints
    `dcmd NAME 0xVALUE size=N dir=...` using get_device_size()/get_device_direction().
    We never re-implement the dcmd bit layout on the host: compile with qcc and run
    it on the target (or with gcc + target/platform/linux_compat for the mock).
 3. Optional AI step (suggest_seeds): an LLM reads the header + comments and proposes
    semantically meaningful payloads per command (e.g. "magic must be ADMN, level 2").
    Output is strictly validated; the LLM never decides dcmd values.
"""
from __future__ import annotations

import json
import os
import re
import urllib.request
from dataclasses import dataclass, field

from .testcase import KIND, MAX_PAYLOAD, Op, TestCase

_DIR = {"__DIOT": "to", "__DIOF": "from", "__DIOTF": "tofrom", "__DION": "none"}
_DIO = re.compile(r"^\s*#\s*define\s+(?P<name>[A-Za-z_]\w*)\s+(?P<macro>__DIOTF|__DIOT|__DIOF|__DION)\s*"
                  r"\(\s*(?P<args>.*)\)\s*$")
_NUM = re.compile(r"^\s*#\s*define\s+(?P<name>[A-Za-z_]\w*)\s+\(?\s*(?P<val>0[xX][0-9a-fA-F]+|\d+)[uUlL]*\s*\)?\s*(?:/[*/].*)?$")
_STR = re.compile(r'^\s*#\s*define\s+(?P<name>[A-Za-z_]\w*)\s+"(?P<val>(?:[^"\\]|\\.)*)"\s*(?:/[*/].*)?$')


@dataclass
class DevctlCmd:
    name: str
    direction: str
    cls: str
    cmd: str
    type: str | None = None
    comment: str = ""


@dataclass
class HeaderInfo:
    commands: list[DevctlCmd] = field(default_factory=list)
    numbers: dict[str, int] = field(default_factory=dict)
    strings: dict[str, str] = field(default_factory=dict)


def _join_continuations(text: str) -> list[str]:
    out, cur = [], ""
    for line in text.splitlines():
        if line.rstrip().endswith("\\"):
            cur += line.rstrip()[:-1] + " "
            continue
        out.append(cur + line)
        cur = ""
    if cur:
        out.append(cur)
    return out


def _split_args(s: str) -> list[str]:
    args, depth, cur = [], 0, ""
    for ch in s:
        if ch == "," and depth == 0:
            args.append(cur.strip())
            cur = ""
            continue
        depth += ch == "("
        depth -= ch == ")"
        cur += ch
    if cur.strip():
        args.append(cur.strip())
    return args


def parse_header(text: str) -> HeaderInfo:
    info = HeaderInfo()
    for line in _join_continuations(text):
        comment = ""
        m_c = re.search(r"/\*(.*?)\*/|//(.*)$", line)
        if m_c:
            comment = (m_c.group(1) or m_c.group(2) or "").strip()
            code = line[:m_c.start()]
        else:
            code = line
        m = _DIO.match(code)
        if m:
            args = _split_args(m["args"])
            want = 2 if m["macro"] == "__DION" else 3
            if len(args) == want:
                info.commands.append(DevctlCmd(m["name"], _DIR[m["macro"]], args[0], args[1],
                                               args[2] if want == 3 else None, comment))
            continue
        m = _NUM.match(line)
        if m:
            info.numbers[m["name"]] = int(m["val"], 0)
            continue
        m = _STR.match(line)
        if m:
            info.strings[m["name"]] = bytes(m["val"], "utf-8").decode("unicode_escape")
    return info


def resolver_source(header_include: str, info: HeaderInfo, pre_includes: tuple[str, ...] | list[str] = ()) -> str:
    """C program that prints dictionary lines with the target's own macros.

    header_include is written verbatim if it is already <...> or "...";
    pre_includes are headers a real system header expects to be included
    first (e.g. <termios.h> for <sys/dcmd_chr.h>'s struct winsize)."""
    inc = header_include if header_include[:1] in "<\"" else f'"{header_include}"'
    pre = [f"#include {h if h[:1] in '<\"' else '<' + h + '>'}" for h in pre_includes]
    lines = [
        "/* Generated by resfuzz dictgen. Build for the target and run there:",
        " *   qcc -Vgcc_ntox86_64 -I<dir of header> -o dcmd_resolver dcmd_resolver.c   (verified on SDP 8.0)",
        " * get_device_size()/get_device_direction()/DEVDIR_* are documented in",
        " * https://www.qnx.com/developers/docs/8.0/com.qnx.doc.neutrino.lib_ref/topic/d/devctl.html */",
        "#include <stdio.h>",
        "#include <devctl.h>",
        *pre,
        f"#include {inc}",
        "",
        "static const char *dir_name(unsigned d)",
        "{",
        '    if (d == DEVDIR_TOFROM) return "tofrom";',
        '    if (d == DEVDIR_TO) return "to";',
        '    if (d == DEVDIR_FROM) return "from";',
        '    return "none";',
        "}",
        "",
        "int main(void)",
        "{",
    ]
    for c in info.commands:
        lines.append(f'    printf("dcmd {c.name} 0x%08x size=%u dir=%s\\n", (unsigned)({c.name}), '
                     f'(unsigned)get_device_size({c.name}), dir_name((unsigned)get_device_direction({c.name})));')
    lines += ["    return 0;", "}", ""]
    return "\n".join(lines)


def _escape(b: bytes) -> str:
    return "".join(chr(x) if 0x20 <= x < 0x7F and chr(x) not in '"\\' else f"\\x{x:02x}" for x in b)


def token_lines(info: HeaderInfo) -> list[str]:
    """Constants become little-endian tokens (u32, or u64 when needed) and raw strings."""
    out = []
    for name, v in info.numbers.items():
        if v < 0x100:
            continue  # small values are covered by the mutator's interesting-value tables
        width = 4 if v <= 0xFFFFFFFF else 8
        if v > 0xFFFFFFFFFFFFFFFF:
            continue
        out.append(f'{name.lower()}="{_escape(v.to_bytes(width, "little"))}"')
    for name, s in info.strings.items():
        b = s.encode("utf-8")[:64]
        if b:
            out.append(f'{name.lower()}="{_escape(b)}"')
    return out


# ------------------------------------------------------------------ AI step
@dataclass
class SeedSuggestion:
    dcmd: str
    payload: bytes
    rationale: str = ""
    claimed_len: int | None = None   # emit a DEVCTL_RAW op that lies about nbytes


SYSTEM_PROMPT = (
    "You help fuzz a QNX resource manager. Given its devctl header, propose test inputs that "
    "reach deep code: valid magic values, privileged modes, boundary sizes, invalid indexes, "
    "and sequences (e.g. set a mode first). Reply ONLY with JSON: "
    '{"seeds":[{"sequence":[{"dcmd":"NAME","payload_hex":"..","claimed_len":null}],"rationale":".."}]}. '
    "Use only dcmd names from the header. Payloads are little-endian, at most 4096 bytes."
)


def parse_suggestions(reply: str, info: HeaderInfo) -> list[list[SeedSuggestion]]:
    """Validate an LLM reply. Unknown names, bad hex, oversize payloads are dropped."""
    m = re.search(r"\{.*\}", reply, flags=re.S)
    if not m:
        return []
    try:
        doc = json.loads(m.group(0))
    except json.JSONDecodeError:
        return []
    known = {c.name for c in info.commands}
    seqs = []
    seeds = doc.get("seeds") if isinstance(doc, dict) else None
    for seed in seeds if isinstance(seeds, list) else []:
        seq = []
        steps = seed.get("sequence") if isinstance(seed, dict) else None
        for step in steps if isinstance(steps, list) else []:
            try:
                name = step["dcmd"]
                payload = bytes.fromhex(step.get("payload_hex", "") or "")
                cl = step.get("claimed_len")
                cl = int(cl) if cl is not None else None
            except (KeyError, ValueError, TypeError, AttributeError):
                seq = []
                break
            if name not in known or len(payload) > MAX_PAYLOAD or (cl is not None and not 0 <= cl < 2**32):
                seq = []
                break
            seq.append(SeedSuggestion(name, payload, str(seed.get("rationale", ""))[:200], cl))
        if seq:
            seqs.append(seq)
    return seqs


def seeds_to_testcases(seqs: list[list[SeedSuggestion]], resolved: dict[str, int]) -> list[TestCase]:
    """resolved: dcmd name -> value as printed by the on-target resolver."""
    out = []
    for seq in seqs:
        if any(s.dcmd not in resolved for s in seq):
            continue
        ops = []
        for s in seq:
            if s.claimed_len is not None:
                ops.append(Op(KIND["DEVCTL_RAW"], 0, resolved[s.dcmd], s.claimed_len, s.payload))
            else:
                ops.append(Op(KIND["DEVCTL"], 0, resolved[s.dcmd], len(s.payload), s.payload))
        out.append(TestCase(ops[:64]))
    return out


def parse_resolved_dict(text: str) -> dict[str, int]:
    res = {}
    for line in text.splitlines():
        p = line.split()
        if len(p) >= 3 and p[0] == "dcmd":
            res[p[1]] = int(p[2], 0)
    return res


class OpenAICompatClient:
    """Minimal OpenAI-compatible chat client configured via environment:
    RESFUZZ_LLM_BASE_URL (e.g. https://api.example.com/v1), RESFUZZ_LLM_API_KEY,
    RESFUZZ_LLM_MODEL. Optional; dictgen works without it."""

    def __init__(self, base_url: str | None = None, api_key: str | None = None, model: str | None = None):
        self.base_url = (base_url or os.environ.get("RESFUZZ_LLM_BASE_URL", "")).rstrip("/")
        self.api_key = api_key or os.environ.get("RESFUZZ_LLM_API_KEY", "")
        self.model = model or os.environ.get("RESFUZZ_LLM_MODEL", "")

    @property
    def configured(self) -> bool:
        return bool(self.base_url and self.model)

    def complete(self, system: str, user: str, timeout: float = 600) -> str:
        body = json.dumps({"model": self.model, "temperature": 0.2, "max_tokens": 1200,
                           "messages": [{"role": "system", "content": system},
                                        {"role": "user", "content": user}]}).encode()
        req = urllib.request.Request(self.base_url + "/chat/completions", data=body, method="POST",
                                     headers={"Content-Type": "application/json",
                                              **({"Authorization": f"Bearer {self.api_key}"} if self.api_key else {})})
        with urllib.request.urlopen(req, timeout=timeout) as r:
            doc = json.loads(r.read())
        return doc["choices"][0]["message"]["content"]


def suggest_seeds(header_text: str, info: HeaderInfo, client) -> list[list[SeedSuggestion]]:
    names = ", ".join(c.name for c in info.commands)
    user = f"devctl commands: {names}\n\nHeader:\n```c\n{header_text[:20000]}\n```"
    return parse_suggestions(client.complete(SYSTEM_PROMPT, user), info)


def build_dictionary(header_text: str, resolved_text: str | None = None) -> str:
    info = parse_header(header_text)
    lines = ["# generated by resfuzz dictgen"]
    if resolved_text:
        lines += [ln for ln in resolved_text.splitlines() if ln.startswith("dcmd ")]
    else:
        lines.append("# dcmd lines missing: run the generated resolver on the target and pass --resolved")
    lines += token_lines(info)
    return "\n".join(lines) + "\n"


def write_seeds(testcases: list[TestCase], out_dir) -> list[str]:
    from pathlib import Path
    d = Path(out_dir)
    d.mkdir(parents=True, exist_ok=True)
    paths = []
    for i, tc in enumerate(testcases):
        p = d / f"ai_seed_{i:03d}.rfz"
        tc.save(p)
        paths.append(str(p))
    return paths

