import json

from resfuzz.report import render_html, render_markdown, write_reports
from resfuzz.testcase import KIND, Op, TestCase
from resfuzz.triage import (gdb_argv, group_findings, load_dict_names, load_events, parse_backtrace,
                            stack_hash, summarize)

BT = """\
Core was generated by `buggy_rm /dev/buggy'.
Program terminated with signal SIGSEGV, Segmentation fault.
#0  0x0000000000401136 in buggy_devctl (dcmd=3222277443, in=0x7ffe, claimed=4) at buggy_logic.c:142
#1  0x00000000004015a0 in io_devctl (ctp=0x1, msg=0x2, ocb=0x3) at buggy_rm.c:88
#2  main () at buggy_rm.c:150
#3  0x00007f00 in ?? ()
"""


def write_events(d, evs, junk=True):
    lines = [json.dumps(e) for e in evs]
    if junk:
        lines.insert(1, "{not json")
        lines.append("[1,2]")
    (d / "events.jsonl").write_text("\n".join(lines) + "\n")


def make_out(tmp_path):
    out = tmp_path / "out"
    (out / "crashes").mkdir(parents=True)
    tc = TestCase([Op(KIND["DEVCTL_RAW"], 0, 0xC0100D43, 0x12, b"\x04\0\0\0")])
    tc.save(out / "crashes" / "crash_aa_0.rfz")
    evs = [
        {"type": "start", "t_ms": 0},
        {"type": "crash", "bucket": "aa", "op": "DEVCTL_RAW", "dcmd": "c0100d43", "signal": 11, "t_ms": 1200,
         "file": "/data/resfuzz/out/crashes/crash_aa_0.rfz", "reproducible": True, "errno": 3, "errno_name": "ESRCH"},
        {"type": "crash", "bucket": "aa", "op": "DEVCTL_RAW", "dcmd": "c0100d43", "signal": 11, "t_ms": 1500},
        {"type": "deadline", "bucket": "bb", "op": "DEVCTL", "dcmd": "c00c0d44", "max_latency_us": 25000,
         "t_ms": 300, "reproducible": False},
        {"type": "hang", "bucket": "cc", "op": "DEVCTL", "dcmd": "c00c0d44", "t_ms": 900, "reproducible": True},
        {"type": "done", "t_ms": 5000},
    ]
    write_events(out, evs)
    (out / "stats.json").write_text(json.dumps({"execs": 1000, "execs_per_s": 200, "elapsed_s": 5,
                                                "coverage": 1, "edges": 77, "deadline_us": 5000,
                                                "platform": "linux-stub"}))
    return out


def test_load_events_tolerates_junk(tmp_path):
    out = make_out(tmp_path)
    evs, bad = load_events(out / "events.jsonl")
    assert len(evs) == 6 and bad == 2
    assert load_events(tmp_path / "missing.jsonl") == ([], 0)


def test_grouping_and_order(tmp_path, ):
    out = make_out(tmp_path)
    evs, _ = load_events(out / "events.jsonl")
    names = load_dict_names([__import__("pathlib").Path(__file__).resolve().parents[2] / "target/examples/buggy_rm.dict"])
    fs = group_findings(evs, out, names)
    assert [f.type for f in fs] == ["crash", "hang", "deadline"]
    c = fs[0]
    assert c.count == 2 and c.reproducible is True and c.signal_name == "SIGSEGV"
    assert c.dcmd_name == "DCMD_BUGGY_GET_STATS"
    assert c.testcase is not None and c.testcase.ops[0].a == 0xC0100D43   # remote path mapped into out/
    assert fs[2].reproducible is False and fs[2].severity == "low"
    assert summarize(fs) == {"crash": 1, "hang": 1, "deadline": 1, "reproducible": 2}


def test_parse_backtrace_and_hash():
    fr = parse_backtrace(BT)
    assert [f.func for f in fr] == ["buggy_devctl", "io_devctl", "main", "??"]
    assert fr[0].file == "buggy_logic.c" and fr[0].line == 142 and fr[0].addr == "0x0000000000401136"
    assert fr[2].addr is None
    moved = BT.replace("0x0000000000401136", "0x0000000000999999")
    assert stack_hash(fr) == stack_hash(parse_backtrace(moved))
    assert stack_hash(fr) != stack_hash(fr[1:])


def test_gdb_argv():
    a = gdb_argv("buggy_rm", "x.core", gdb="ntox86_64-gdb")
    assert a[0] == "ntox86_64-gdb" and a[-2:] == ["buggy_rm", "x.core"] and "bt" in a


def test_reports_escape_untrusted(tmp_path):
    out = make_out(tmp_path)
    evs, _ = load_events(out / "events.jsonl")
    fs = group_findings(evs, out)
    fs[0].frames = parse_backtrace("#0  0x1 in evil<script>alert(1)</script> () at x.c:1")
    stats = json.loads((out / "stats.json").read_text())
    h = render_html(fs, stats, {"target": "/dev/<b>buggy</b>", "generated": "now"})
    assert "<script>" not in h and "&lt;script&gt;" in h and "<b>buggy" not in h
    assert "http" not in h.split("<style>")[0]  # self-contained: no external resources
    m = render_markdown(fs, stats, {"target": "/dev/buggy"})
    assert "| 1 | high |" in m and "--replay crashes/crash_aa_0.rfz" in m
    md, ht = write_reports(out, fs, stats, {"target": "/dev/buggy"})
    assert md.exists() and ht.exists()


